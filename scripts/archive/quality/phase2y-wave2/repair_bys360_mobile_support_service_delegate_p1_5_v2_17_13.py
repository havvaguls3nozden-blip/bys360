from __future__ import annotations

import argparse
import ast
import json
import os
import re
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

VERSION = "V2.17.13"
REPORT_NAME = "bys360_mobile_support_service_delegate_p1_5_v2_17_13_report"
TARGET_NAMES = [
    "mobile_support_ticket_create",
    "mobile_support_ticket_detail",
    "mobile_support_ticket_reply",
    "mobile_support_ticket_close",
    "mobile_support_ticket_rate",
    "mobile_support_tickets",
    "mobile_support_ticket_list",
    "mobile_support_categories",
    "mobile_support_ticket_categories",
]

DELEGATE_MARKER = "# BYS360_P1_5_SUPPORT_SERVICE_DELEGATE"


def rel(path: Path, root: Path) -> str:
    try:
        return path.relative_to(root).as_posix()
    except Exception:
        return path.as_posix()


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="")


def parse_module(path: Path):
    text = read_text(path)
    return text, ast.parse(text)


def function_nodes(path: Path):
    text, tree = parse_module(path)
    return text, [n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]


def has_route_decorator(node: ast.AST) -> bool:
    decorators = getattr(node, "decorator_list", [])
    for dec in decorators:
        s = ast.unparse(dec) if hasattr(ast, "unparse") else ""
        if ".route(" in s or s.endswith(".route") or "route(" in s:
            return True
    return False


def arg_names(node: ast.FunctionDef) -> list[str]:
    args = []
    for a in getattr(node.args, "posonlyargs", []):
        args.append(a.arg)
    for a in node.args.args:
        args.append(a.arg)
    if node.args.vararg:
        args.append("*" + node.args.vararg.arg)
    for a in node.args.kwonlyargs:
        args.append(f"{a.arg}={a.arg}")
    if node.args.kwarg:
        args.append("**" + node.args.kwarg.arg)
    return args


def candidate_functions(routes_path: Path) -> dict:
    text, nodes = function_nodes(routes_path)
    candidates = []
    for node in nodes:
        name = node.name
        if name in TARGET_NAMES or ("support" in name.lower() and name.startswith("mobile_")):
            block = text.splitlines()[node.lineno-1: node.end_lineno]
            delegated = DELEGATE_MARKER in "\n".join(block) or f"_bys360_legacy_{name}" in text and f"{name}_service" in "\n".join(block)
            candidates.append({
                "name": name,
                "lineno": node.lineno,
                "end_lineno": node.end_lineno,
                "line_count": node.end_lineno - node.lineno + 1,
                "has_route_decorator": has_route_decorator(node),
                "delegated": delegated,
                "args": arg_names(node),
            })
    return {"text": text, "candidates": candidates}


def replace_or_append_service(service_path: Path, service_name: str, legacy_name: str) -> bool:
    service_path.parent.mkdir(parents=True, exist_ok=True)
    if not service_path.exists():
        write_text(service_path, '"""Mobile support service delegates.\n\nGenerated by BYS360 P1.5 safe route refactor.\n"""\n\n')
    text = read_text(service_path)
    function_code = (
        f"def {service_name}(*args, **kwargs):\n"
        f"    \"\"\"Delegate to legacy mobile support route body without changing URL/endpoint.\"\"\"\n"
        f"    from app.api.mobile import routes as _routes\n"
        f"    return _routes.{legacy_name}(*args, **kwargs)\n"
    )
    try:
        tree = ast.parse(text)
        lines = text.splitlines()
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == service_name:
                start = node.lineno - 1
                end = node.end_lineno
                new_lines = lines[:start] + function_code.rstrip("\n").splitlines() + lines[end:]
                new_text = "\n".join(new_lines) + "\n"
                if new_text != text:
                    write_text(service_path, new_text)
                    return True
                return False
    except SyntaxError:
        # If the scaffold was damaged, preserve it next to the new content.
        backup = service_path.with_suffix(service_path.suffix + ".before_p1_5_parse_error")
        shutil.copy2(service_path, backup)
        text = '"""Mobile support service delegates.\n\nGenerated by BYS360 P1.5 safe route refactor.\n"""\n\n'
    if service_name not in text:
        if text and not text.endswith("\n"):
            text += "\n"
        text += "\n" + function_code
        write_text(service_path, text)
        return True
    return False


def make_wrapper_and_legacy(text: str, node: ast.FunctionDef) -> str:
    lines = text.splitlines()
    dec_start = min([d.lineno for d in node.decorator_list], default=node.lineno) - 1
    def_start = node.lineno - 1
    end = node.end_lineno
    decorator_lines = lines[dec_start:def_start]
    def_line = lines[def_start]
    original_def_block = lines[def_start:end]
    legacy_name = f"_bys360_legacy_{node.name}"
    service_name = f"{node.name}_service"
    call_args = ", ".join(arg_names(node))
    call_expr = f"_svc({call_args})" if call_args else "_svc()"

    # Rename only the first def occurrence in the original block.
    original_block_text = "\n".join(original_def_block)
    original_block_text = re.sub(rf"^(\s*)(async\s+def|def)\s+{re.escape(node.name)}\s*\(", rf"\1\2 {legacy_name}(", original_block_text, count=1, flags=re.M)

    wrapper_lines = []
    wrapper_lines.extend(decorator_lines)
    wrapper_lines.append(def_line)
    wrapper_lines.append(f"    {DELEGATE_MARKER}")
    wrapper_lines.append(f"    from app.api.mobile.services.support_service import {service_name} as _svc")
    wrapper_lines.append(f"    return {call_expr}")
    wrapper_text = "\n".join(wrapper_lines)
    return wrapper_text + "\n\n" + original_block_text


def patch_routes(root: Path, report: dict) -> dict:
    routes_path = root / "app" / "api" / "mobile" / "routes.py"
    service_path = root / "app" / "api" / "mobile" / "services" / "support_service.py"
    result = {"routes_changed": False, "service_changed": False, "patched_functions": [], "skipped": [], "backup": "", "error": ""}
    if not routes_path.exists():
        result["error"] = "routes.py bulunamadi"
        return result
    text, tree = parse_module(routes_path)
    nodes = [n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]
    targets = []
    for node in nodes:
        if node.name in TARGET_NAMES or ("support" in node.name.lower() and node.name.startswith("mobile_")):
            if not has_route_decorator(node):
                result["skipped"].append({"name": node.name, "reason": "route decorator yok"})
                continue
            block_text = "\n".join(text.splitlines()[node.lineno-1: node.end_lineno])
            if DELEGATE_MARKER in block_text or f"_bys360_legacy_{node.name}" in text:
                result["skipped"].append({"name": node.name, "reason": "zaten delege/legacy var"})
                continue
            targets.append(node)
    if not targets:
        return result

    qroot = root / "_local_quarantine" / f"bys360_mobile_support_delegate_p1_5_{datetime.now().strftime('%Y%m%d_%H%M%S')}" / "app" / "api" / "mobile"
    qroot.mkdir(parents=True, exist_ok=True)
    backup_path = qroot / "routes.py.before_p1_5"
    shutil.copy2(routes_path, backup_path)
    result["backup"] = rel(backup_path, root)

    lines = text.splitlines()
    # Replace from bottom to top to preserve line numbers.
    new_text = text
    for node in sorted(targets, key=lambda n: n.lineno, reverse=True):
        current_lines = new_text.splitlines()
        dec_start = min([d.lineno for d in node.decorator_list], default=node.lineno) - 1
        end = node.end_lineno
        block = make_wrapper_and_legacy(new_text, node)
        current_lines = current_lines[:dec_start] + block.splitlines() + current_lines[end:]
        new_text = "\n".join(current_lines) + "\n"
        service_name = f"{node.name}_service"
        legacy_name = f"_bys360_legacy_{node.name}"
        if replace_or_append_service(service_path, service_name, legacy_name):
            result["service_changed"] = True
        result["patched_functions"].append(node.name)

    try:
        ast.parse(new_text)
    except SyntaxError as exc:
        shutil.copy2(backup_path, routes_path)
        result["error"] = f"patched routes syntax error, rollback yapildi: {exc}"
        return result
    write_text(routes_path, new_text)
    result["routes_changed"] = True
    return result


def run_cmd(root: Path, cmd: list[str], timeout: int = 90) -> dict:
    try:
        p = subprocess.run(cmd, cwd=str(root), text=True, encoding="utf-8", errors="replace", stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=timeout)
        return {"ok": p.returncode == 0, "returncode": p.returncode, "stdout_tail": p.stdout[-5000:], "stderr_tail": p.stderr[-5000:]}
    except Exception as exc:
        return {"ok": False, "returncode": -1, "stdout_tail": "", "stderr_tail": str(exc)}


def health(root: Path) -> dict:
    compile_res = run_cmd(root, [sys.executable, "-m", "compileall", "app", "config.py", "scripts"], 180)
    app_res = run_cmd(root, [sys.executable, "-c", "from app import create_app; app=create_app(); print('BYS360_APP_CREATE_OK', len(app.blueprints))"], 120)
    return {"compileall_ok": compile_res["ok"], "app_factory_ok": app_res["ok"] and "BYS360_APP_CREATE_OK" in app_res.get("stdout_tail", ""), "overall_ok": compile_res["ok"] and app_res["ok"] and "BYS360_APP_CREATE_OK" in app_res.get("stdout_tail", ""), "compileall": compile_res, "app_factory": app_res}


def write_report(root: Path, report: dict) -> None:
    reports = root / "reports" / "quality"
    reports.mkdir(parents=True, exist_ok=True)
    json_path = reports / f"{REPORT_NAME}.json"
    md_path = reports / f"{REPORT_NAME}.md"
    report["json_report"] = rel(json_path, root)
    report["md_report"] = rel(md_path, root)
    json_path.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    cands = report.get("audit", {}).get("candidates", [])
    apply = report.get("apply", {})
    hs = report.get("health_summary", {})
    md = []
    md.append(f"# BYS360 Mobile Support Service Delegate P1.5 {VERSION}\n")
    md.append("Bu rapor mobil destek/support route fonksiyonlarının URL, endpoint ve blueprint adı korunarak servis delegasyonuna alınma sonucunu gösterir.\n")
    md.append("## Audit\n")
    md.append(f"- candidate_count: {len(cands)}")
    md.append("\n| Fonksiyon | Satır | Route | Delegated | Arg |")
    md.append("|---|---:|---:|---:|---|")
    for c in cands:
        md.append(f"| `{c['name']}` | {c['lineno']} | {c['has_route_decorator']} | {c['delegated']} | `{', '.join(c.get('args', []))}` |")
    md.append("\n## Apply\n")
    for k in ["routes_changed", "service_changed", "patched_functions", "skipped", "backup", "error"]:
        md.append(f"- {k}: {apply.get(k, '')}")
    md.append("\n## Sağlık Kontrolü\n")
    md.append(f"- compileall_ok: {hs.get('compileall_ok')}")
    md.append(f"- app_factory_ok: {hs.get('app_factory_ok')}")
    md.append(f"- overall_ok: {hs.get('overall_ok')}\n")
    md_path.write_text("\n".join(md), encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--project-root", required=True)
    ap.add_argument("--mode", choices=["audit", "apply", "health", "all"], default="audit")
    args = ap.parse_args()
    root = Path(args.project_root).resolve()
    report = {"version": VERSION, "mode": args.mode, "project_root": str(root), "audit": {}, "apply": {}, "health_summary": {}}
    routes_path = root / "app" / "api" / "mobile" / "routes.py"
    if args.mode in ("audit", "all", "apply"):
        if routes_path.exists():
            cand = candidate_functions(routes_path)
            report["audit"] = {"candidates": cand["candidates"]}
        else:
            report["audit"] = {"error": "routes.py bulunamadi", "candidates": []}
    if args.mode in ("apply", "all"):
        report["apply"] = patch_routes(root, report)
    if args.mode in ("health", "all"):
        report["health_summary"] = health(root)
    write_report(root, report)
    print(json.dumps({k: v for k, v in report.items() if k not in ("audit",)}, ensure_ascii=False, indent=2))
    apply = report.get("apply", {})
    hs = report.get("health_summary", {})
    print("BYS360_MOBILE_SUPPORT_SERVICE_DELEGATE_P1_5_V2_17_13_REPORT_OK")
    if args.mode in ("health", "all") and hs.get("overall_ok"):
        print("BYS360_MOBILE_SUPPORT_SERVICE_DELEGATE_P1_5_V2_17_13_HEALTH_OK")
    if args.mode in ("apply", "all"):
        if apply.get("routes_changed"):
            print("BYS360_MOBILE_SUPPORT_SERVICE_DELEGATE_P1_5_V2_17_13_APPLY_OK")
        else:
            print("BYS360_MOBILE_SUPPORT_SERVICE_DELEGATE_P1_5_V2_17_13_APPLY_NOOP")
    print("BYS360_MOBILE_SUPPORT_SERVICE_DELEGATE_P1_5_V2_17_13_OK")
    if args.mode in ("health", "all") and not hs.get("overall_ok"):
        return 1
    # NOOP is not a failure for this package.
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
